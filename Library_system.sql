CREATE TABLE publisher (
    publisher_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    publisher_name VARCHAR2(100) NOT NULL UNIQUE, 
    address VARCHAR2(200) NOT NULL , 
    contact_number VARCHAR2(20)
);

CREATE TABLE author (
    author_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY , 
    first_name VARCHAR2(50) NOT NULL , 
    last_name VARCHAR2(50) NOT NULL , 
    nationality VARCHAR2(50), 
    birth_date DATE 
);

CREATE TABLE book (
    book_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY , 
    book_title VARCHAR2(150) NOT NULL , 
    isbn VARCHAR2(20) NOT NULL UNIQUE ,
    publication_year NUMBER(4) NOT NULL , 
    genre VARCHAR2(50) NOT NULL , 
    publisher_id NUMBER(10) NOT NULL , 
    author_id NUMBER(10) NOT NULL,
    status VARChAR2(20) DEFAULT 'AVAILABLE' NOT NULL ,
    CONSTRAINT pk_book PRIMARY KEY(book_id),

    CONSTRAINT fk_book_publisher
        FOREIGN KEY (publisher_id)
        REFERENCES publisher(publisher_id),
    CONSTRAINT fk_author
        FOREIGN KEY (author_id)
        REFERENCES author(author_id)
);

CREATE TABLE member (
    member_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    first_name VARCHAR2(50) NOT NULL , 
    last_name VARCHAR2(50) NOT NULL , 
    email VARCHAR2(100) NOT NULL UNIQUE , 
    contact_number VARCHAR2(20) NOT NULL , 
    registration_date DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE librarian (
    librarian_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY , 
    first_name VARCHAR2(50) NOT NULL , 
    last_name VARCHAR2(50) NOT NULL , 
    email VARCHAR2(100) NOT NULL UNIQUE, 
    hire_date DATE DEFAULT SYSDATE NOT NULL ,
    salary NUMBER (10, 2) NOT NULL
);