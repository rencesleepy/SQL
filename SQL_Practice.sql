SELECT * FROM STUDENTS
WHERE COURSE = 'BSCS';

SELECT * FROM STUDENTS
WHERE AGE = 19
OR AGE = 22
AND COURSE = 'BSCS';


-- sorting
SELECT * FROM STUDENTS
ORDER BY AGE ASC; -- youngest to oldest

SELECT * FROM STUDENTS
ORDER BY AGE DESC; -- oldest to youngest


-- counting
SELECT COURSE, COUNT(*) AS TOTAL_STUDENTS
FROM STUDENTS
GROUP BY COURSE; -- count students per course

SELECT AGE, COUNT (*) AS TOTAL_STUDENTS
FROM STUDENTS
GROUP BY AGE; -- number of students per age


-- having
SELECT COURSE, COUNT(*) AS TOTAL_STUDENTS
FROM STUDENTS
GROUP BY COURSE
HAVING COUNT(*) > 1; -- show only courses with more than 1 student

SELECT AGE, COUNT(*) AS TOTAL_STUDENTS
FROM STUDENTS
GROUP BY AGE
HAVING COUNT(*) > 1; -- show number of students in an age


-- avg, min, max
SELECT AVG(AGE) AS AVERAGE_AGE
FROM STUDENTS;

SELECT MIN(AGE) AS YOUNGEST_AGE
FROM STUDENTS;

SELECT MAX(AGE) AS OLDEST_AGE
FROM STUDENTS;

SELECT
    AVG(AGE) AS AVERAGE_AGE,
    MIN(AGE) AS YOUNGEST_AGE,
    MAX(AGE) AS OLDEST_AGE
FROM STUDENTS;


-- group by AVG()
SELECT COURSE, AVG(AGE) AS AVERAGE_AGE
FROM STUDENTS
GROUP BY COURSE;



CREATE TABLE STUDENTS (
    student_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    first_name VARCHAR2(50) NOT NULL, 
    last_name VARCHAR2(50) NOT NULL, 
    AGE NUMBER CHECK (AGE >= 18),
    course VARCHAR2(30) NOT NULL , 
    email VARCHAR2(100) UNIQUE
);



--insert into grades
SELECT student_id, first_name, last_name
FROM STUDENTS
ORDER BY student_id;


CREATE TABLE GRADES (
    grade_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER(10),
    subject VARCHAR2(50) NOT NULL, 
    grade NUMBER(5,2) CHECK (GRADE BETWEEN 0 AND 100), 

    CONSTRAINT FK_STUDENT
        FOREIGN KEY(student_id)
        REFERENCES STUDENTS(STUDENT_ID)
);

