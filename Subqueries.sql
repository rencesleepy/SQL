-- 1. Subquery with IN: Find customers who have placed orders over 30 dollars
SELECT first_name, last_name 
FROM customers 
WHERE customer_id IN (
    SELECT customer_id 
    FROM orders 
    WHERE total_amount > 30.00
);


-- 2. Scalar Subquery in SELECT: Show order ID alongside the average total order amount
SELECT order_id, total_amount,
       (SELECT AVG(total_amount) FROM orders) AS overall_avg_amount
FROM orders;

-- 3. Subquery in FROM clause (Inline View): Calculate average order value per customer via derived table
SELECT cust_summary.customer_id, cust_summary.order_count
FROM (
    SELECT customer_id, COUNT(*) AS order_count
    FROM orders
    GROUP BY customer_id
) cust_summary
WHERE cust_summary.order_count > 0;

-- 4. Subquery with NOT IN: Find menu items that have never been ordered
SELECT item_name 
FROM menu_items 
WHERE item_id NOT IN (
    SELECT item_id 
    FROM order_items
);


-- 5. Subquery with ALL: Find the most expensive item on the menu
SELECT item_name, price 
FROM menu_items 
WHERE price >= ALL (
    SELECT price 
    FROM menu_items
);

-- 6. Correlated Subquery in WHERE: Find orders whose amount is higher than the customer's average order amount
SELECT order_id, customer_id, total_amount
FROM orders o1
WHERE total_amount > (
    SELECT AVG(total_amount)
    FROM orders o2
    WHERE o2.customer_id = o1.customer_id
);

-- 7. Subquery with HAVING: Find categories where the average item price exceeds 15.00
SELECT menu_items.category_id, AVG(price) AS avg_price
FROM menu_items
GROUP BY menu_items.category_id
HAVING AVG(price) > (
    SELECT AVG(price) FROM menu_items
);

