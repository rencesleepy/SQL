-- 1. Customers Table
CREATE TABLE customers (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    email VARCHAR2(100) UNIQUE,
    phone VARCHAR2(20),
    created_date DATE DEFAULT SYSDATE
);

-- 2. Categories Table
CREATE TABLE categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(50) NOT NULL UNIQUE
);

-- 3. Menu Items Table
CREATE TABLE menu_items (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id NUMBER REFERENCES categories(category_id),
    item_name VARCHAR2(100) NOT NULL,
    price NUMBER(10, 2) NOT NULL,
    is_available CHAR(1) DEFAULT 'Y' CHECK (is_available IN ('Y', 'N'))
);

-- 4. Orders Table
CREATE TABLE orders (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER REFERENCES customers(customer_id),
    order_date DATE DEFAULT SYSDATE,
    total_amount NUMBER(10, 2) DEFAULT 0,
    status VARCHAR2(20) DEFAULT 'Pending' CHECK (status IN ('Pending', 'Completed', 'Cancelled'))
);

-- 5. Order Items Table
CREATE TABLE order_items (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER REFERENCES orders(order_id) ON DELETE CASCADE,
    item_id NUMBER REFERENCES menu_items(item_id),
    quantity NUMBER(5) NOT NULL CHECK (quantity > 0),
    unit_price NUMBER(10, 2) NOT NULL
);

