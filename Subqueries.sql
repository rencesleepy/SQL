CREATE OR REPLACE VIEW vw_customer_orders AS
SELECT
    c.customer_id,
    c.first_name || ' ' || c.last_name AS customer_name,
    o.order_id,
    o.order_date,
    o.total_amount,
    o.status
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id;
SELECT * FROM VW_CUSTOMER_ORDERS;

-- 3. View for detailed order contents
CREATE OR REPLACE VIEW vw_order_details AS
SELECT
    o.order_id,
    m.item_name,
    oi.quantity,
    oi.unit_price,
    (oi.quantity * oi.unit_price) AS line_total
FROM orders o
JOIN order_items oi ON o.order_id = oi.order_id
JOIN menu_items m ON oi.item_id = m.item_id;
SELECT * FROM vw_order_details;

-- 4. View for category item counts
CREATE OR REPLACE VIEW vw_category_item_counts AS
SELECT
    c.category_name,
    COUNT(m.item_id) AS total_items
FROM categories c
LEFT JOIN menu_items m ON c.category_id = m.category_id
GROUP BY c.category_name;
SELECT * FROM vw_category_item_counts;