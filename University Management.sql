CREATE TABLE department_university (
    department_university_id NUMBER(10) PRIMARY KEY,
    department_name VARCHAR2(100) NOT NULL UNIQUE,
    location VARCHAR2(100),
    contact_number VARCHAR2(20)
);
CREATE TABLE professor (
    professor_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    specialization VARCHAR2(80) NOT NULL,
    email VARCHAR2(100),
    department_university_id NUMBER(10) NOT NULL,
    CONSTRAINT pk_professor PRIMARY KEY (professor_id),
    CONSTRAINT uk_professor_email UNIQUE (email),
    CONSTRAINT fk_professor_department
        FOREIGN KEY (department_university_id)
        REFERENCES department_university(department_university_id)
);
CREATE TABLE student (
    student_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    birth_date DATE NOT NULL,
    gender VARCHAR2(10) NOT NULL,
    email VARCHAR2(100),
    department_university_id NUMBER(10) NOT NULL,
    CONSTRAINT pk_student PRIMARY KEY (student_id),
    CONSTRAINT uk_student_email UNIQUE (email),
    CONSTRAINT fk_student_department
        FOREIGN KEY (department_university_id)
        REFERENCES department_university(department_university_id)
);

CREATE TABLE classroom (
    room_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    room_number VARCHAR2(20) NOT NULL,
    building_name VARCHAR2(100) NOT NULL,
    capacity NUMBER(3) NOT NULL,
    status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,

    CONSTRAINT pk_classroom PRIMARY KEY (room_id),
    CONSTRAINT uk_classroom_number UNIQUE (room_number)
);

CREATE TABLE course (
    course_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    course_name VARCHAR2(100) NOT NULL,
    course_code VARCHAR2(20) NOT NULL,
    units NUMBER(2) NOT NULL,
    professor_id NUMBER(10) NOT NULL,
    room_id NUMBER(10) NOT NULL,

    CONSTRAINT pk_course PRIMARY KEY (course_id),
    CONSTRAINT uk_course_code UNIQUE (course_code),

    CONSTRAINT fk_course_professor
        FOREIGN KEY (professor_id)
        REFERENCES professor(professor_id),

    CONSTRAINT fk_course_room
        FOREIGN KEY (room_id)
        REFERENCES classroom(room_id)
);

CREATE TABLE enrollment (
    enrollment_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    student_id NUMBER(10) NOT NULL,
    course_id NUMBER(10) NOT NULL,
    enrollment_date DATE DEFAULT SYSDATE NOT NULL,
    semester VARCHAR2(20) NOT NULL,
    school_year VARCHAR2(20) NOT NULL,
    grade NUMBER(5,2),

    CONSTRAINT pk_enrollment PRIMARY KEY (enrollment_id),

    CONSTRAINT fk_enrollment_student
        FOREIGN KEY (student_id)
        REFERENCES student(student_id),

    CONSTRAINT fk_enrollment_course
        FOREIGN KEY (course_id)
        REFERENCES course(course_id)
);
